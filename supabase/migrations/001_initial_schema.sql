-- ============================================================================
-- 1. TABELAS
-- ============================================================================

-- 1.1. Proprietários (privada — nunca exposta publicamente)
create table if not exists public.owners (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  phone text,
  notes text,
  created_at timestamptz not null default now()
);

comment on table public.owners is 'Cadastro privado de proprietários. Acesso restrito a usuários autenticados.';

-- 1.2. Imóveis (leitura pública apenas quando status = disponivel; owner_id nunca exposto a anon)
create table if not exists public.properties (
  id uuid primary key default gen_random_uuid(),
  code integer generated by default as identity (start with 101) unique not null,
  slug text unique not null,
  title text not null,
  type text not null check (type in ('casa', 'apartamento', 'terreno', 'comercial')),
  purpose text not null check (purpose in ('venda', 'locacao')),
  price numeric(12, 2) check (price is null or price >= 0),
  condo_fee numeric(10, 2) check (condo_fee is null or condo_fee >= 0),
  iptu numeric(10, 2) check (iptu is null or iptu >= 0),
  area_total numeric(10, 2) check (area_total is null or area_total >= 0),
  area_built numeric(10, 2) check (area_built is null or area_built >= 0),
  bedrooms integer not null default 0 check (bedrooms >= 0),
  suites integer not null default 0 check (suites >= 0),
  bathrooms integer not null default 0 check (bathrooms >= 0),
  parking integer not null default 0 check (parking >= 0),
  condominium text,
  neighborhood text,
  city text not null default 'Cotia',
  address text,
  description text,
  status text not null default 'disponivel' check (
    status in ('disponivel', 'reservado', 'vendido', 'alugado', 'rascunho')
  ),
  is_featured boolean not null default false,
  owner_id uuid references public.owners(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.properties is 'Carteira de imóveis. Leitura pública restrita a imóveis com status = disponivel.';

-- 1.3. Imagens dos imóveis (leitura pública; escrita restrita a autenticados)
create table if not exists public.property_images (
  id uuid primary key default gen_random_uuid(),
  property_id uuid not null references public.properties(id) on delete cascade,
  url text not null,
  position integer not null default 0 check (position >= 0),
  created_at timestamptz not null default now()
);

comment on table public.property_images is 'Galeria de imagens dos imóveis (position = 0 indica foto de capa).';

-- 1.4. Leads / Mini-CRM (insert público via site; leitura e gestão restritas a autenticados)
create table if not exists public.leads (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  phone text not null,
  email text,
  source text not null default 'site' check (
    source in ('site', 'whatsapp', 'indicacao', 'newcore', 'olx', 'marketplace')
  ),
  property_id uuid references public.properties(id) on delete set null,
  status text not null default 'novo' check (
    status in ('novo', 'em_contato', 'visita', 'proposta', 'fechado', 'perdido')
  ),
  notes text,
  last_contact_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

comment on table public.leads is 'Interessados captados pelo site ou cadastrados manualmente no Mini-CRM.';

-- ============================================================================
-- 2. TRIGGER DE ATUALIZAÇÃO AUTOMÁTICA (updated_at)
-- ============================================================================

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_properties_updated_at on public.properties;
create trigger trg_properties_updated_at
  before update on public.properties
  for each row
  execute function public.set_updated_at();

